"""Structural contracts implemented by system adapters."""
from typing import Protocol, List, Dict
from rdp_session_manager.domain.users import RDPUser
from rdp_session_manager.domain.sessions import SessionInfo


class UserRepository(Protocol):
    def list_users(self) -> List[RDPUser]: ...
    def get_user(self, username: str) -> RDPUser: ...
    def diagnose_user(self, username: str) -> Dict: ...


class SessionRepository(Protocol):
    def get_active_sessions(self) -> List[SessionInfo]: ...
    def get_ip_address(self) -> str: ...
    def invalidate(self) -> None: ...


class Dispatcher(Protocol):
    def __call__(self, callback) -> object: ...
